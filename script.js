let currentImages = [];
let currentIndex = 0;

function openModal(propKey) {
    const data = propertiesData[propKey];
    if (!data) return;

    document.getElementById('modalPrice').innerText = data.price;
    document.getElementById('modalTitle').innerText = data.title;
    document.getElementById('modalDescription').innerHTML = data.description;
    document.getElementById('modalWspBtn').href = data.wspUrl;

    const mapBtn = document.getElementById('modalMapBtn');
    if (data.mapUrl && data.mapUrl.trim() !== '') {
        mapBtn.href = data.mapUrl;
        mapBtn.style.display = 'block';
    } else {
        mapBtn.style.display = 'none';
    }

    currentImages = data.images || [];
    currentIndex = 0;

    updateMainImage();
    renderThumbs();

    document.getElementById('propertyModal').classList.add('active');
    document.body.style.overflow = 'hidden';
}

